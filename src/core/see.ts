import { Chess, type Square } from "chess.js";

/** Conventional piece values in pawns. The king's value only matters for ordering captures. */
export const PIECE_VALUE: Record<string, number> = { p: 1, n: 3, b: 3, r: 5, q: 9, k: 100 };

export interface MoveSquares {
  from: string;
  to: string;
  promotion?: string;
}

export function uciToSquares(uci: string): MoveSquares {
  return { from: uci.slice(0, 2), to: uci.slice(2, 4), promotion: uci.length > 4 ? uci.slice(4, 5) : undefined };
}

/**
 * What the side to move can still win on `square` by capturing there with its least valuable piece,
 * given that the other side recaptures the same way. Never negative: a side can always decline.
 * Legal moves are generated by chess.js, so pins and pieces lined up behind each other are respected.
 */
function bestRecapture(chess: Chess, square: Square): number {
  const captures = chess
    .moves({ verbose: true })
    .filter((move) => move.to === square && move.captured)
    .sort((a, b) => (PIECE_VALUE[a.piece] ?? 0) - (PIECE_VALUE[b.piece] ?? 0));
  const capture = captures[0];
  if (!capture) return 0;
  const victim = PIECE_VALUE[capture.captured ?? ""] ?? 0;
  chess.move(capture);
  const gain = victim - bestRecapture(chess, square);
  chess.undo();
  return Math.max(0, gain);
}

/**
 * Static exchange evaluation: the material, in pawns, that a capture wins or loses once every
 * sensible recapture on the same square has been played. Returns null if the move is not a legal capture.
 */
export function staticExchange(fen: string, move: MoveSquares): number | null {
  const chess = new Chess(fen);
  let played;
  try {
    played = chess.move(move);
  } catch {
    // chess.js throws on an illegal move; for this question that simply means "not a capture here".
    return null;
  }
  if (!played.captured) return null;
  const promotionGain = played.promotion ? (PIECE_VALUE[played.promotion] ?? 0) - 1 : 0;
  const captured = PIECE_VALUE[played.captured] ?? 0;
  return captured + promotionGain - bestRecapture(chess, played.to);
}
